def bookshelf(W='#8a5a3e', w='#6a4230', D='#3e2620', G='#f2c24a', books=('#ff9dbd', '#9ad8c0', '#b8a4f0', '#ffd98a', '#f7c4a8', '#8ab0e8')):
    """書庫の本棚（3段。本の色と高さはばらばら）"""
    g = rows('''
        ..wWWWWWWWWWWWWWWWWWWw..
        .wWGGGGGGGGGGGGGGGGGGWw.
        .wWWWWWWWWWWWWWWWWWWWWw.
        .wWDDDDDDDDDDDDDDDDDDWw.
        .wWD................DWw.
        .wWD................DWw.
        .wWD................DWw.
        .wWD................DWw.
        .wWWWWWWWWWWWWWWWWWWWWw.
        .wwwwwwwwwwwwwwwwwwwwww.
        .wWDDDDDDDDDDDDDDDDDDWw.
        .wWD................DWw.
        .wWD................DWw.
        .wWD................DWw.
        .wWD................DWw.
        .wWWWWWWWWWWWWWWWWWWWWw.
        .wwwwwwwwwwwwwwwwwwwwww.
        .wWDDDDDDDDDDDDDDDDDDWw.
        .wWD................DWw.
        .wWD................DWw.
        .wWD................DWw.
        .wWD................DWw.
        .wWWWWWWWWWWWWWWWWWWWWw.
        .wwwwwwwwwwwwwwwwwwwwww.
        .wWWWWWWWWWWWWWWWWWWWWw.
        .wwwwwwwwwwwwwwwwwwwwww.
        ..DDDDDDDDDDDDDDDDDDDD..
    ''')
    im = render(pad(g, 24, 32, y=3), dict(W=W, w=w, D=D, G=G))
    p = im.load()
    import random
    from core import hexc
    rnd = random.Random(5)
    for shelf_y in (7, 14, 21):  # 各段の本（下がそろう）
        x = 4
        while x < 20:
            bw = rnd.choice((1, 2, 2, 3))
            bh = rnd.randrange(3, 5)
            col = hexc(rnd.choice(books))
            dk = tuple(round(c * .7) for c in col[:3]) + (255,)
            for xx in range(x, min(20, x + bw)):
                for yy in range(shelf_y + 3 - bh + 1, shelf_y + 4):
                    p[xx, yy] = dk if xx == x + bw - 1 and bw > 1 else col
                p[xx, shelf_y + 3 - bh + 1] = tuple(min(255, round(c * 1.15)) for c in col[:3]) + (255,)
            if rnd.random() < .15 and x + bw < 19:  # 傾いた本
                p[x + bw, shelf_y + 3] = col
                x += 1
            x += bw
    return im


